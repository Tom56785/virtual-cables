# Regenerates LICENSES/Rust-crates.txt: the licence and notice of every Rust
# crate compiled into the Windows executable. Run it after changing
# dependencies:
#
#     powershell -ExecutionPolicy Bypass -File scripts\update-licenses.ps1
#
# Crates used only while building (procedural macros and their dependencies,
# and build-script dependencies such as the icon resizer) are not part of the
# executable and are left out.

$ErrorActionPreference = 'Stop'
$target = 'x86_64-pc-windows-gnu'
$root = Split-Path -Parent $PSScriptRoot
$output = Join-Path $root 'LICENSES\Rust-crates.txt'

Push-Location $root
try {
    $metadata = cargo metadata --format-version 1 --filter-platform $target | ConvertFrom-Json
    if ($LASTEXITCODE -ne 0) { throw 'cargo metadata failed' }
    $rootPackage = $metadata.resolve.root

    # Runtime dependencies only: normal edges, without procedural macros.
    $tree = cargo tree -e normal,no-proc-macro --target $target --prefix none --format '{p}'
    if ($LASTEXITCODE -ne 0) { throw 'cargo tree failed' }
    $crates = $tree |
        ForEach-Object { ($_ -replace ' \(\*\)$', '') -replace ' \(.*\)$', '' } |
        Where-Object { $_ -match '^\S+ v\S+$' } |
        Sort-Object -Unique |
        ForEach-Object {
            $name, $version = $_ -split ' v'
            $metadata.packages | Where-Object { $_.name -eq $name -and $_.version -eq $version }
        } |
        Where-Object { $_.id -ne $rootPackage } |
        Sort-Object name, version

    # Where a crate offers MIT, its MIT notice is used.
    $noticeFiles = 'LICENSE-MIT', 'license-mit', 'LICENSE-MIT.md', 'LICENSE', 'LICENSE.md', 'LICENSE.txt', 'COPYING'
    $rule = '-' * 72
    $text = New-Object System.Text.StringBuilder
    $lines = @(
        'Third-party Rust crates compiled into Virtual Cables'
        '===================================================='
        ''
        'The Windows executable includes code from the crates below. Each is'
        'distributed under the licence shown; where a crate offers a choice of'
        'licences, Virtual Cables uses it under the MIT licence, whose notice is'
        'reproduced below. Crates used only while building (procedural macros and'
        'the icon resizer) are not part of the executable and are not listed.'
        ''
        'Generated by scripts/update-licenses.ps1.'
        ''
    )
    foreach ($line in $lines) { [void]$text.Append("$line`n") }

    foreach ($crate in $crates) {
        $dir = Split-Path -Parent $crate.manifest_path
        $notice = $noticeFiles | Where-Object { Test-Path -LiteralPath (Join-Path $dir $_) -PathType Leaf } | Select-Object -First 1
        foreach ($line in @($rule, "$($crate.name) $($crate.version)", "Licence: $($crate.license)",
                "Source:  $($crate.repository)", "Notice:  $notice", $rule, '')) {
            [void]$text.Append("$line`n")
        }
        if ($notice) {
            $content = [IO.File]::ReadAllText((Join-Path $dir $notice)) -replace "`r", ''
            [void]$text.Append($content)
            if (-not $content.EndsWith("`n")) { [void]$text.Append("`n") }
        } else {
            [void]$text.Append("(NO LICENCE FILE FOUND - check the crate's repository)`n")
            Write-Warning "$($crate.name) $($crate.version) has no licence file"
        }
        [void]$text.Append("`n")
    }

    [IO.File]::WriteAllText($output, $text.ToString(), (New-Object System.Text.UTF8Encoding $false))
    Write-Host "Wrote $output with $(@($crates).Count) crates:"
    $crates | ForEach-Object { Write-Host "  $($_.name) $($_.version)  [$($_.license)]" }
} finally {
    Pop-Location
}
